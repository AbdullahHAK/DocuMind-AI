def resolve_evidence(ev: dict, file_index: dict[str, dict], where: str) -> dict:
    path = ev.get("file")
    if not path or not (ROOT / path).is_file():
        errors.append(f"{where}: evidence file not found: {path!r}")
        return {**ev, "broken": True}
    out = {"file": path}
    if "symbol" in ev:
        sid = f"sym:{path}#{ev['symbol']}"
        sym = next((s for s in file_index.get(path, {}).get("symbols", []) if s["id"] == sid), None)
        if not sym:
            errors.append(f"{where}: symbol {ev['symbol']!r} not found in {path}")
            return {**ev, "broken": True}
        out.update(symbol=ev["symbol"], symbol_id=sid, lines=sym["lines"])
    elif "match" in ev:
        text = read(path)
        m = re.search(ev["match"], text, re.M)
        if not m:
            errors.append(f"{where}: pattern {ev['match']!r} not found in {path}")
            return {**ev, "broken": True}
        start = text[: m.start()].count("\n") + 1
        end = text[: m.end()].count("\n") + 1
        out.update(match=ev["match"], lines=[start, end])
    elif "lines" in ev:
        n = len(read(path).splitlines())
        a, b = ev["lines"]
        if not (1 <= a <= b <= n):
            errors.append(f"{where}: lines {a}-{b} out of range for {path} ({n} lines)")
        out["lines"] = ev["lines"]
    if "note" in ev:
        out["note"] = ev["note"]
    return out


def walk_evidence(obj, file_index, where: str):
    """Resolve every {"evidence": [...]} list found anywhere in the curated data."""
    if isinstance(obj, dict):
        for key, value in list(obj.items()):
            if key == "evidence" and isinstance(value, list):
                obj[key] = [resolve_evidence(ev, file_index, f"{where}") for ev in value]
            else:
                label = obj.get("id", where) if isinstance(obj.get("id"), str) else where
                walk_evidence(value, file_index, label)
    elif isinstance(obj, list):
        for item in obj:
            walk_evidence(item, file_index, where)


