def main() -> int:
    all_files = list_files()
    excluded, analysed = [], []
    for f in all_files:
        reason = next((why for rx, why in EXCLUDE_RULES if rx.search(f)), None)
        (excluded if reason else analysed).append((f, reason))
    analysed_paths = [f for f, _ in analysed]
    file_set = set(all_files)

    # module index for python import resolution
    module_index = {}
    for f in analysed_paths:
        if f.endswith(".py"):
            module_index[py_module_name(f)] = f

    file_info: dict[str, dict] = {}
    for f in analysed_paths:
        text = read(f) if not f.endswith(".pdf") else ""
        info = {
            "id": f"file:{f}",
            "path": f,
            "name": Path(f).name,
            "dir": Path(f).parent.as_posix(),
            "layer": layer_of(f),
            "lines": len(text.splitlines()),
            "lang": Path(f).suffix.lstrip(".") or Path(f).name,
            "doc": "",
            "imports": [],
            "symbols": [],
        }
        try:
            if f.endswith(".py"):
                py = analyse_python(f, module_index)
                info.update(py)
                tree = ast.parse(text)
                info["doc"] = docline(tree)
            elif f.endswith((".ts", ".tsx")):
                info.update(analyse_ts(f, file_set))
                first = re.match(r"\s*/\*\*?(.*?)\*/|\s*//\s*(.*)", text, re.S)
                if first:
                    info["doc"] = (first.group(1) or first.group(2) or "").strip().strip("*").strip().splitlines()[0]
            elif f.endswith(".md"):
                heads = re.findall(r"^#{1,3}\s+(.+)$", text, re.M)
                info["headings"] = heads[:40]
                info["doc"] = heads[0] if heads else ""
        except SyntaxError as exc:
            errors.append(f"parse error in {f}: {exc}")
        file_info[f] = info

    # ---------------------------------------------------------------- relationships (generated)
    edges: list[dict] = []
    symbols: list[dict] = []
    sym_by_module_name: dict[tuple[str, str], str] = {}
    for f, info in file_info.items():
        for s in info.get("symbols", []):
            symbols.append(s)
            mod = info.get("module")
            if mod:
                sym_by_module_name[(mod, s["name"])] = s["id"]

    for f, info in file_info.items():
        for imp in info.get("imports", []):
            if imp.get("file") and imp["file"] in file_info:
                edges.append({"id": f"imports:{f}->{imp['file']}", "type": "imports", "source": f"file:{f}",
                              "target": f"file:{imp['file']}", "status": "verified",
                              "evidence": [{"file": f, "lines": [imp["line"], imp["line"]]}],
                              "label": ", ".join(imp["names"][:6])})
        for s in info.get("symbols", []):
            edges.append({"id": f"contains:{f}->{s['id']}", "type": "contains", "source": f"file:{f}",
                          "target": s["id"], "status": "verified"})

    # python call edges by static name resolution
    seen_calls = set()
    for f, info in file_info.items():
        if not f.endswith(".py"):
            continue
        mod = info.get("module")
        names = info.get("imported_names", {})
        local = {s["name"]: s["id"] for s in info["symbols"]}
        for s in info["symbols"]:
            for raw in s.get("calls_raw", []):
                target = None
                head, _, tail = raw.partition(".")
                if raw in local:
                    target = local[raw]
                elif raw.startswith("self.") and s.get("parent"):
                    cls = s["name"].split(".")[0]
                    target = local.get(f"{cls}.{raw[5:]}")
                elif head in names and not tail:
                    m, _, sym = names[head].partition(":")
                    target = sym_by_module_name.get((m, sym))
                elif head in names and tail:
                    m, _, sym = names[head].partition(":")
                    target = sym_by_module_name.get((m, f"{sym}.{tail}")) if sym else sym_by_module_name.get((m, tail))
                if target and target != s["id"] and (s["id"], target) not in seen_calls:
                    seen_calls.add((s["id"], target))
                    edges.append({"id": f"calls:{s['id']}->{target}", "type": "calls", "source": s["id"],
                                  "target": target, "status": "inferred",
                                  "note": "static name resolution (method calls on injected objects are not resolved)"})
        for s in info["symbols"]:
            s.pop("calls_raw", None)

    # TS: component renders component, function calls API endpoint
    ts_symbols = {s["name"]: s["id"] for s in symbols if s["file"].endswith((".ts", ".tsx"))}
    for f, info in file_info.items():
        if not f.endswith((".ts", ".tsx")):
            continue
        for s in info["symbols"]:
            for comp in s.get("jsx", []):
                if comp in ts_symbols and ts_symbols[comp] != s["id"]:
                    edges.append({"id": f"renders:{s['id']}->{ts_symbols[comp]}", "type": "renders", "source": s["id"],
                                  "target": ts_symbols[comp], "status": "verified"})
            for name in set(s.get("calls_raw", [])):
                if name in ts_symbols and ts_symbols[name] != s["id"] and name[0].islower():
                    edges.append({"id": f"calls:{s['id']}->{ts_symbols[name]}", "type": "calls", "source": s["id"],
                                  "target": ts_symbols[name], "status": "inferred", "note": "regex call detection"})
            s.pop("calls_raw", None)

    # endpoints
    endpoints = []
    for f, info in file_info.items():
        for r in info.get("routes", []):
            eid = f"api:{r['method']} {r['path']}"
            endpoints.append({"id": eid, "name": f"{r['method']} {r['path']}", **r})
            edges.append({"id": f"handles:{eid}", "type": "handled_by", "source": eid, "target": r["handler"],
                          "status": "verified"})
    # frontend -> endpoint
    for s in symbols:
        for url in s.get("api_urls", []):
            # template literals: `${expr}` becomes a path segment placeholder
            normalised = re.sub(r"\$\{[^}]*\}?", "x", url)
            best = None
            for e in endpoints:
                pattern = re.sub(r"\{[^}]+\}", r"[^/]+", e["path"])
                if re.match(pattern + r"(?![A-Za-z0-9_/])|" + pattern + r"(?=[^/]*$)", normalised) and (
                    best is None or len(e["path"]) > len(best["path"])
                ):
                    if re.match(pattern + "($|[^/])", normalised) or normalised == e["path"]:
                        best = e
            if best:
                edges.append({"id": f"http:{s['id']}->{best['id']}", "type": "sends_request_to", "source": s["id"],
                              "target": best["id"], "status": "verified", "label": "fetch",
                              "evidence": [{"file": s["file"], "lines": s["lines"]}]})

    # tests -> modules (by import)
    tests = []
    for f, info in file_info.items():
        if info["layer"] != "tests" or not f.endswith(".py"):
            continue
        targets = sorted({imp["file"] for imp in info["imports"] if imp.get("file", "") and
                          imp["file"].startswith("backend/app/")})
        tests.append({"id": f"test:{f}", "file": f, "test_functions": len(info.get("tests", [])),
                      "names": [t.split("#", 1)[1] for t in info.get("tests", [])], "covers": targets})
        for t in targets:
            edges.append({"id": f"tested_by:{t}->{f}", "type": "tested_by", "source": f"file:{t}",
                          "target": f"file:{f}", "status": "verified", "note": "test file imports this module"})

    env_vars = [s for info in file_info.values() for s in info.get("settings", [])]

    # ---------------------------------------------------------------- curated layer
    curated = json.loads((DATA / "curated.json").read_text(encoding="utf-8"))
    walk_evidence(curated, file_info, "curated")

    entity_ids = {f"file:{f}" for f in file_info} | {s["id"] for s in symbols} | {e["id"] for e in endpoints} \
        | {v["id"] for v in env_vars} | {t["id"] for t in tests}
    for group in ("groups", "components", "data_entities", "deployment", "findings", "flows", "decisions", "concepts"):
        for item in curated.get(group, []):
            entity_ids.add(item["id"])

    for drel in curated.get("data_relations", []):
        for end in ("source", "target"):
            if drel[end] not in entity_ids:
                errors.append(f"data relation {drel['id']}: unknown {end} {drel[end]!r}")
    for ent in curated.get("data_entities", []):
        for key in ("written_by", "read_by", "deleted_by"):
            for ref in ent.get(key, []):
                if ref not in entity_ids:
                    errors.append(f"data entity {ent['id']}: {key} references unknown {ref!r}")
        if ent.get("store") not in entity_ids:
            errors.append(f"data entity {ent['id']}: unknown store {ent.get('store')!r}")
    for concept in curated.get("concepts", []):
        for ref in concept.get("related", []):
            if ref not in entity_ids:
                errors.append(f"concept {concept['id']}: unknown related {ref!r}")
    for comp in curated.get("components", []):
        if comp.get("group") not in entity_ids:
            errors.append(f"component {comp['id']}: unknown group {comp.get('group')!r}")

    # curated relations must reference known entities
    for rel_ in curated.get("relations", []):
        for end in ("source", "target"):
            if rel_[end] not in entity_ids:
                errors.append(f"relation {rel_.get('id')}: unknown {end} {rel_[end]!r}")
    for comp in curated.get("components", []) + curated.get("data_entities", []) + curated.get("deployment", []):
        for f in comp.get("files", []):
            if f"file:{f}" not in entity_ids and not (ROOT / f).exists():
                errors.append(f"{comp['id']}: listed file does not exist: {f}")
        for link in comp.get("related", []):
            if link not in entity_ids:
                errors.append(f"{comp['id']}: related id unknown: {link}")
    for flow in curated.get("flows", []):
        participants = {p["id"] for p in flow.get("participants", [])}
        for step in flow.get("steps", []):
            for end in ("from", "to"):
                if step[end] not in participants:
                    errors.append(f"flow {flow['id']}: step references unknown participant {step[end]!r}")
        for p in flow.get("participants", []):
            if p.get("ref") and p["ref"] not in entity_ids:
                errors.append(f"flow {flow['id']}: participant ref unknown {p['ref']!r}")
    for f in curated.get("findings", []):
        if not f.get("evidence"):
            errors.append(f"finding {f['id']} has no evidence")
    for e in edges:
        for end in ("source", "target"):
            if e[end] not in entity_ids:
                errors.append(f"edge {e['id']}: unknown {end} {e[end]!r}")

    # dependents (reverse imports) for the file catalog
    dependents = defaultdict(list)
    for e in edges:
        if e["type"] == "imports":
            dependents[e["target"]].append(e["source"])
    tested_by = defaultdict(list)
    for e in edges:
        if e["type"] == "tested_by":
            tested_by[e["source"]].append(e["target"])
    for f, info in file_info.items():
        info["dependents"] = sorted(dependents.get(f"file:{f}", []))
        info["tested_by"] = sorted(tested_by.get(f"file:{f}", []))
        info.pop("imported_names", None)
        info["symbols"] = [s["id"] for s in info.get("symbols", [])]
        info["tests"] = info.get("tests", [])
        info.pop("routes", None)
        info.pop("settings", None)

    # ---------------------------------------------------------------- reports embedded in the viewer
    reports = []
    for p in sorted(REPORTS.glob("*.md")):
        reports.append({"id": f"report:{p.stem}", "file": rel(p), "title": p.stem, "markdown": p.read_text(encoding="utf-8")})

    git = lambda *a: subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True).stdout.strip()  # noqa: E731
    atlas = {
        "meta": {
            "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "git_commit": git("rev-parse", "--short", "HEAD"),
            "git_dirty": bool(git("status", "--porcelain")),
            "counts": {
                "files_analysed": len(file_info), "files_excluded": len(excluded), "symbols": len(symbols),
                "edges": len(edges), "endpoints": len(endpoints), "env_vars": len(env_vars), "test_files": len(tests),
                "test_functions": sum(t["test_functions"] for t in tests),
            },
            "status_legend": {
                "verified": "directly established by code or configuration",
                "partial": "some, but not all, of the path is confirmed",
                "inferred": "plausible interpretation that still needs validation",
                "unknown": "evidence is insufficient",
            },
        },
        "files": list(file_info.values()),
        "excluded": [{"path": f, "reason": r} for f, r in excluded],
        "symbols": symbols,
        "edges": edges,
        "endpoints": endpoints,
        "env_vars": env_vars,
        "tests": tests,
        **curated,
        "reports": reports,
        "errors": errors,
    }

    write_generated_reports(atlas)
    # re-embed (generated reports were just written)
    atlas["reports"] = [
        {"id": f"report:{p.stem}", "file": rel(p), "title": p.stem, "markdown": p.read_text(encoding="utf-8")}
        for p in sorted(REPORTS.glob("*.md"))
    ]

    DATA.mkdir(exist_ok=True)
    payload = json.dumps(atlas, indent=1, ensure_ascii=False)
    (DATA / "atlas.json").write_text(payload, encoding="utf-8")
    (DATA / "atlas.js").write_text("window.ATLAS = " + payload + ";\n", encoding="utf-8")

    c = atlas["meta"]["counts"]
    print(f"atlas: {c['files_analysed']} files, {c['symbols']} symbols, {c['edges']} edges, "
          f"{c['endpoints']} endpoints, {c['env_vars']} settings, {c['test_functions']} tests")
    if errors:
        print(f"\n{len(errors)} VALIDATION ERROR(S):")
        for e in errors:
            print("  -", e)
        return 1
    print("validation: all evidence references and graph edges resolve")
    return 0


def write_generated_reports(atlas: dict) -> None:
    files = {f["path"]: f for f in atlas["files"]}
    sym = {s["id"]: s for s in atlas["symbols"]}
    by_layer = defaultdict(list)
    for f in atlas["files"]:
        by_layer[f["layer"]].append(f)

    out = ["# 03 · Module and file catalog", "",
           "_Generated by `tools/build_atlas.py` from the source code. Do not edit by hand._", "",
           f"{len(files)} files analysed · {len(atlas['symbols'])} symbols · commit `{atlas['meta']['git_commit']}`"
           + (" (working tree had uncommitted changes)" if atlas["meta"]["git_dirty"] else ""), ""]
    for layer in sorted(by_layer):
        out += [f"## {layer}", ""]
        for f in sorted(by_layer[layer], key=lambda x: x["path"]):
            out.append(f"### `{f['path']}` ({f['lines']} lines)")
            if f.get("doc"):
                out.append(f"{f['doc']}")
            syms = [sym[s] for s in f.get("symbols", []) if s in sym]
            if syms:
                out.append("")
                out.append("| Symbol | Kind | Lines | Summary |")
                out.append("|---|---|---|---|")
                for s in syms:
                    summary = (s.get("doc") or s.get("signature") or "").replace("|", "\\|")
                    out.append(f"| `{s['name']}` | {s['kind']} | {s['lines'][0]}-{s['lines'][1]} | {summary} |")
            imports = sorted({i["file"] for i in f.get("imports", []) if i.get("file")})
            if imports:
                out.append(f"\n**Imports (repo):** " + ", ".join(f"`{i}`" for i in imports))
            if f.get("dependents"):
                out.append("**Used by:** " + ", ".join(f"`{d[5:]}`" for d in f["dependents"]))
            if f.get("tested_by"):
                out.append("**Tested by:** " + ", ".join(f"`{d[5:]}`" for d in f["tested_by"]))
            out.append("")
    (REPORTS / "03-module-and-file-catalog.md").write_text("\n".join(out) + "\n", encoding="utf-8")

    cov = ["# 14 · Coverage inventory", "",
           "_Generated by `tools/build_atlas.py`. Lists every file git knows about (tracked or untracked, not ignored)._",
           "", "## Analysed", "",
           "| File | Layer | Lines | Symbols | Imported by | Tests |", "|---|---|---|---|---|---|"]
    for f in sorted(atlas["files"], key=lambda x: x["path"]):
        cov.append(f"| `{f['path']}` | {f['layer']} | {f['lines']} | {len(f.get('symbols', []))} | "
                   f"{len(f.get('dependents', []))} | {len(f.get('tested_by', []))} |")
    cov += ["", "## Excluded from analysis", "", "| File | Reason |", "|---|---|"]
    for e in atlas["excluded"]:
        cov.append(f"| `{e['path']}` | {e['reason']} |")
    untested = [f["path"] for f in atlas["files"]
                if f["path"].startswith("backend/app/") and f["path"].endswith(".py")
                and not f.get("tested_by") and f["lines"] > 0]
    cov += ["", "## Backend modules with no test file importing them directly", ""]
    cov += [f"- `{p}`" for p in untested] or ["- none"]
    cov += ["", "Note: a module can still be exercised indirectly (e.g. through `tests/test_api.py`).", "",
            "## Not analysed by tooling (and why)", "",
            "- `.env` files are git-ignored and never read by the atlas: secret values are not part of it.",
            "- `backend/storage/` and `backend/.cache/` are runtime state (git-ignored).",
            "- `frontend/node_modules/`, `frontend/dist/`, `backend/.venv/` are dependencies/build output."]
    (REPORTS / "14-coverage-inventory.md").write_text("\n".join(cov) + "\n", encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
