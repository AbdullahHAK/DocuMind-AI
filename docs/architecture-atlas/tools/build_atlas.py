def py_module_name(path: str) -> str | None:
    """backend/app/ingest/pdf.py -> app.ingest.pdf ; backend/eval/common.py -> common (eval sys.path hack)."""
    p = Path(path)
    if path.startswith("backend/"):
        parts = list(Path(path).relative_to("backend").with_suffix("").parts)
        if parts[-1] == "__init__":
            parts = parts[:-1]
        if parts and parts[0] in ("eval",):
            return parts[-1]  # eval scripts import `common` directly
        return ".".join(parts)
    return p.stem


def docline(node) -> str:
    if not isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        return ""
    doc = ast.get_docstring(node)
    return doc.strip().splitlines()[0] if doc else ""


def analyse_python(path: str, module_index: dict[str, str]) -> dict:
    source = read(path)
    tree = ast.parse(source, filename=path)
    imports: list[dict] = []
    imported_names: dict[str, str] = {}  # local name -> "module:symbol" or "module"
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            target = module_index.get(node.module)
            for alias in node.names:
                local = alias.asname or alias.name
                imported_names[local] = f"{node.module}:{alias.name}"
            imports.append({"module": node.module, "names": [a.name for a in node.names], "line": node.lineno,
                            "file": target})
        elif isinstance(node, ast.Import):
            for alias in node.names:
                imported_names[alias.asname or alias.name] = alias.name
                imports.append({"module": alias.name, "names": [], "line": node.lineno,
                                "file": module_index.get(alias.name)})

    symbols: list[dict] = []
    module = py_module_name(path)

    def add_symbol(node, kind: str, qual: str, parent: str | None):
        sym = {
            "id": f"sym:{path}#{qual}",
            "name": qual,
            "kind": kind,
            "file": path,
            "lines": [node.lineno, getattr(node, "end_lineno", node.lineno)],
            "doc": docline(node),
            "parent": parent,
            "calls_raw": [],
        }
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            args = [a.arg for a in node.args.args + node.args.kwonlyargs if a.arg not in ("self", "cls")]
            sym["signature"] = f"{node.name}({', '.join(args)})"
            sym["decorators"] = [ast.unparse(d) for d in node.decorator_list]
            for sub in ast.walk(node):
                if isinstance(sub, ast.Call):
                    sym["calls_raw"].append(ast.unparse(sub.func))
        symbols.append(sym)
        return sym

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            add_symbol(node, "function", node.name, None)
        elif isinstance(node, ast.ClassDef):
            add_symbol(node, "class", node.name, None)
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    add_symbol(sub, "method", f"{node.name}.{sub.name}", f"sym:{path}#{node.name}")
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for t in targets:
                if isinstance(t, ast.Name) and t.id.isupper():
                    add_symbol(node, "constant", t.id, None)

    # FastAPI routes
    routes = []
    for sym in symbols:
        for dec in sym.get("decorators", []):
            m = re.match(r"router\.(get|post|put|delete|patch)\((['\"])(.+?)\2(.*)\)", dec)
            if m:
                status = re.search(r"status_code=(\d+)", m.group(4))
                routes.append({"method": m.group(1).upper(), "path": "/api" + m.group(3), "handler": sym["id"],
                               "status_code": int(status.group(1)) if status else 200})

    # pydantic Settings fields (env vars)
    settings_fields = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == "Settings":
            for sub in node.body:
                if isinstance(sub, ast.AnnAssign) and isinstance(sub.target, ast.Name):
                    name = sub.target.id
                    default = ast.unparse(sub.value) if sub.value is not None else None
                    secret = any(k in name for k in ("key", "token", "secret", "password"))
                    # comments on the same line explain the setting
                    line = source.splitlines()[sub.lineno - 1]
                    comment = line.split("#", 1)[1].strip() if "#" in line else ""
                    settings_fields.append({
                        "id": f"env:{name.upper()}",
                        "name": name.upper(),
                        "field": name,
                        "type": ast.unparse(sub.annotation),
                        "default": "<unset>" if secret else default,
                        "secret": secret,
                        "comment": comment,
                        "lines": [sub.lineno, sub.end_lineno],
                        "file": path,
                    })

    tests = []
    if Path(path).name.startswith("test_"):
        for sym in symbols:
            if sym["kind"] == "function" and sym["name"].startswith("test_"):
                tests.append(sym["id"])

    return {"module": module, "imports": imports, "imported_names": imported_names, "symbols": symbols,
            "routes": routes, "settings": settings_fields, "tests": tests}


# ---------------------------------------------------------------------------
# TypeScript analysis (regex: good enough for this small, conventional code base)
# ---------------------------------------------------------------------------

TS_IMPORT = re.compile(r"""^import\s+(?:type\s+)?(.+?)\s+from\s+['"](.+?)['"]""", re.M)
TS_DECL = re.compile(
    r"^(export\s+)?(?:default\s+)?(?:async\s+)?(function|const|class|interface|type)\s+([A-Za-z_][A-Za-z0-9_]*)", re.M
)
TS_API_URL = re.compile(r"['\"`](/api/[^'\"`]*)")


def resolve_ts(from_path: str, spec: str, files: set[str]) -> str | None:
    if not spec.startswith("."):
        return None
    base = (Path(from_path).parent / spec).as_posix()
    base = str(Path(base).as_posix())
    norm = Path(base)
    parts = []
    for part in norm.parts:
        if part == "..":
            parts.pop()
        elif part != ".":
            parts.append(part)
    base = "/".join(parts)
    for cand in (base, base + ".ts", base + ".tsx", base + "/index.ts", base + "/index.tsx"):
        if cand in files:
            return cand
    return None


def analyse_ts(path: str, files: set[str]) -> dict:
    source = read(path)
    lines = source.splitlines()
    imports = []
    for m in TS_IMPORT.finditer(source):
        line = source[: m.start()].count("\n") + 1
        imports.append({"module": m.group(2), "names": [n.strip() for n in re.split(r"[{},]", m.group(1)) if n.strip()],
                        "line": line, "file": resolve_ts(path, m.group(2), files)})
    decls = list(TS_DECL.finditer(source))
    symbols = []
    for i, m in enumerate(decls):
        start = source[: m.start()].count("\n") + 1
        end = (source[: decls[i + 1].start()].count("\n")) if i + 1 < len(decls) else len(lines)
        name, kind = m.group(3), m.group(2)
        is_component = path.endswith(".tsx") and kind == "function" and name[0].isupper()
        body = "\n".join(lines[start - 1 : end])
        symbols.append({
            "id": f"sym:{path}#{name}",
            "name": name,
            "kind": "component" if is_component else ("type" if kind in ("interface", "type") else kind),
            "file": path,
            "lines": [start, max(start, end)],
            "exported": bool(m.group(1)) or "export default" in lines[start - 1],
            "doc": "",
            "api_urls": sorted(set(TS_API_URL.findall(body))),
            "calls_raw": re.findall(r"\b([A-Za-z_][A-Za-z0-9_]*)\s*\(", body),
            "jsx": sorted(set(re.findall(r"<([A-Z][A-Za-z0-9]*)\b", body))),
        })
    return {"imports": imports, "symbols": symbols}


