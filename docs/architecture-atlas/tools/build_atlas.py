"""Build the Architecture Atlas data from the repository.

Two inputs:
  1. The source code itself, analysed statically (Python AST, TS/TSX regex).
     This produces the *generated* layer: every file, symbol, line range,
     import, call edge, HTTP route, setting and test. Status: "verified"
     (directly read from code) except call edges, which are "inferred"
     (static name resolution can miss dynamic dispatch).
  2. data/curated.json, written by hand: components, flows, data entities,
     deployment, findings. Every evidence reference there names a file plus a
     symbol, a regex or a line range; this script resolves it to real line
     numbers and FAILS if a reference doesn't resolve - so curated claims
     can't silently drift away from the code.

Outputs (in docs/architecture-atlas/):
  data/atlas.json      the full model (version-controllable, diffable)
  data/atlas.js        the same, as `window.ATLAS = {...}` so index.html works from file://
  reports/03-module-and-file-catalog.md   generated
  reports/14-coverage-inventory.md        generated

Run from anywhere (stdlib only, Python 3.10+):
  python docs/architecture-atlas/tools/build_atlas.py
"""

