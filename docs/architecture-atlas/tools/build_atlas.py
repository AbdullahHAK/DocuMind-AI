ATLAS = Path(__file__).resolve().parent.parent
ROOT = ATLAS.parent.parent
DATA = ATLAS / "data"
REPORTS = ATLAS / "reports"

# Files that are not hand-written source: listed in the coverage inventory, not analysed.
EXCLUDE_RULES = [
    (re.compile(r"^docs/architecture-atlas/"), "the atlas itself"),
    (re.compile(r"package-lock\.json$"), "generated lockfile"),
    (re.compile(r"\.pdf$"), "binary document (generated by scripts/make_sample_policy.py)"),
    (re.compile(r"(^|/)(eval|redteam)/results/.*\.json$"), "recorded run output (data, summarised in reports)"),
    (re.compile(r"\.(png|jpg|svg|ico)$"), "image asset"),
]

LAYER_RULES = [
    (r"^backend/app/api\.py$", "backend · http"),
    (r"^backend/app/main\.py$", "backend · entrypoint"),
    (r"^backend/app/services\.py$", "backend · composition root"),
    (r"^backend/app/config\.py$", "backend · configuration"),
    (r"^backend/app/ingest/", "backend · ingestion"),
    (r"^backend/app/(indexer|graph)\.py$", "backend · ingestion"),
    (r"^backend/app/(retrieval|query_expansion|vectorstore|embeddings)\.py$", "backend · retrieval"),
    (r"^backend/app/(answering|prompts|llm|verification|costs|plan_facts)\.py$", "backend · answering"),
    (r"^backend/app/security\.py$", "backend · security"),
    (r"^backend/app/(documents|ratelimit|models|schemas)\.py$", "backend · domain & state"),
    (r"^backend/app/", "backend"),
    (r"^backend/tests/", "tests"),
    (r"^backend/eval/", "evaluation"),
    (r"^backend/redteam/", "security testing"),
    (r"^backend/scripts/", "tooling"),
    (r"^backend/scratch/", "scratch"),
    (r"^backend/data/federal/", "knowledge base"),
    (r"^backend/data/", "data"),
    (r"^frontend/src/components/", "frontend · components"),
    (r"^frontend/src/", "frontend"),
    (r"^frontend/", "frontend · tooling"),
    (r"^\.github/", "ci"),
    (r"(^|/)Dockerfile$|^\.dockerignore$", "deployment"),
    (r"^docs/|\.md$", "documentation"),
    (r".*", "config"),
]

errors: list[str] = []


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def list_files() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout
    return sorted({line.strip() for line in out.splitlines() if line.strip() and (ROOT / line.strip()).is_file()})


def layer_of(path: str) -> str:
    for pattern, layer in LAYER_RULES:
        if re.search(pattern, path):
            return layer
    return "other"


def read(path: str) -> str:
    return (ROOT / path).read_text(encoding="utf-8", errors="replace")


